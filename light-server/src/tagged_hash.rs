impl TaggedSha256 {
    pub fn from_tag_hash(tag_hash: [u8; 32]) -> Self {
        let mut base = Sha256::new();
        base.update(tag_hash);
        base.update(tag_hash);
        Self { base }
    }

    pub fn hasher(&self) -> Sha256 {
        self.base.clone()
    }

    pub fn digest_32(&self, data: impl AsRef<[u8]>) -> [u8; 32] {
        let mut hasher = self.hasher();
        hasher.update(data.as_ref());
        hasher.finalize().into()
    }
}
